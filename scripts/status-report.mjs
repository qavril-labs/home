// Builds the "what works today" status from two sources: docs/status/modules.json (maturity and the test
// files that prove each module) and reports/tests.json (the results of the latest run, written by CI).
// Writes docs/status/WHAT_WORKS_TODAY.md and site/status.html. Nothing here is hand-typed test counts.
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const register = JSON.parse(readFileSync(join(root, "docs/status/modules.json"), "utf8"));
const reportPath = join(root, "reports/tests.json");
const report = existsSync(reportPath) ? JSON.parse(readFileSync(reportPath, "utf8")) : null;

const commit = process.env.GITHUB_SHA?.slice(0, 7) ?? safeGit("rev-parse --short HEAD");
const generatedAt = new Date().toISOString();
// The same base address the site generator uses, so every canonical link matches the sitemap.
const BASE = (process.env.SITE_BASE_URL || "https://your-domain.example").replace(/\/$/, "");

// Results per test file, keyed by the path relative to the repository root.
const files = (report?.testResults ?? []).map((file) => {
  const path = relative(root, file.name).split("\\").join("/");
  const results = file.assertionResults ?? [];
  return {
    path,
    passed: results.filter((item) => item.status === "passed").length,
    failed: results.filter((item) => item.status !== "passed").length,
  };
});

const modules = register.modules.map((module) => {
  const matched = files.filter((file) => module.tests.some((prefix) => file.path === prefix || file.path.startsWith(prefix)));
  const passed = matched.reduce((sum, file) => sum + file.passed, 0);
  const failed = matched.reduce((sum, file) => sum + file.failed, 0);
  return { ...module, passed, failed, measured: report !== null && module.tests.length > 0 };
});

const totals = {
  passed: files.reduce((sum, file) => sum + file.passed, 0),
  failed: files.reduce((sum, file) => sum + file.failed, 0),
};
const labels = {
  AVAILABLE: "Available",
  EARLY_ACCESS: "Early access",
  IN_DEVELOPMENT: "In development",
  PROTOTYPE: "Prototype",
  PLANNED: "Planned",
};

function testsCell(module) {
  if (module.tests.length === 0) return "No tests yet";
  if (!module.measured) return "Not measured in this run";
  return `${module.passed} passed${module.failed ? `, ${module.failed} failing` : ""}`;
}

// Markdown for the repository.
const markdown = [
  "# What works today",
  "",
  `Generated ${generatedAt} from commit \`${commit}\`. Test counts come from the CI run. Do not edit this file by hand.`,
  "",
  report
    ? `Latest run: ${totals.passed} tests passed, ${totals.failed} failing, across ${files.length} test files.`
    : "No test report was found, so no test counts are shown.",
  "",
  "| Module | Status | Tests | What it does |",
  "|---|---|---|---|",
  ...modules.map((module) => `| ${module.id} ${module.name} | ${labels[module.status]} | ${testsCell(module)} | ${module.summary} |`),
  "",
  "## Status definitions",
  "",
  ...Object.entries(register.definitions).map(([key, text]) => `- **${labels[key]}**: ${text}`),
  "",
].join("\n");

// HTML for the website, using the site's stylesheet and no scripts.
const escape = (value) => String(value).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const rows = modules
  .map(
    (module) => `        <tr>
          <th scope="row">${escape(module.id)} ${escape(module.name)}</th>
          <td><span class="tag">${escape(labels[module.status])}</span></td>
          <td>${escape(testsCell(module))}</td>
          <td>${escape(module.summary)}</td>
        </tr>`,
  )
  .join("\n");
const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>What works today | QAVRIL LABS</title>
  <meta name="description" content="Each QAVRIL LABS module, its honest status, and the test results from the latest automated run.">
  <link rel="canonical" href="${BASE}/status.html">
  <meta name="robots" content="index, follow">
  <meta property="og:type" content="website">
  <meta property="og:title" content="What works today | QAVRIL LABS">
  <meta property="og:description" content="Each QAVRIL LABS module, its honest status, and the test results from the latest automated run.">
  <meta property="og:url" content="${BASE}/status.html">
  <meta name="twitter:card" content="summary">
  <link rel="stylesheet" href="styles.css">
</head>
<body>
  <main>
    <h1>What works today</h1>
    <p class="lead">${escape(report ? `Latest automated run: ${totals.passed} tests passed, ${totals.failed} failing.` : "No automated test report is attached to this page yet.")}</p>
    <p class="fine">Generated ${escape(generatedAt)} from commit ${escape(commit)}. Statuses follow the definitions below and change only when the evidence changes.</p>
    <table>
      <thead><tr><th scope="col">Module</th><th scope="col">Status</th><th scope="col">Tests</th><th scope="col">What it does</th></tr></thead>
      <tbody>
${rows}
      </tbody>
    </table>
    <h2>Status definitions</h2>
    <ul>
${Object.entries(register.definitions).map(([key, text]) => `      <li><strong>${escape(labels[key])}:</strong> ${escape(text)}</li>`).join("\n")}
    </ul>
  </main>
</body>
</html>
`;

mkdirSync(join(root, "docs/status"), { recursive: true });
writeFileSync(join(root, "docs/status/WHAT_WORKS_TODAY.md"), markdown, "utf8");
mkdirSync(join(root, "site"), { recursive: true });
writeFileSync(join(root, "site/status.html"), html, "utf8");
console.log(`status report: ${modules.length} modules, ${totals.passed} passed, ${totals.failed} failing${report ? "" : " (no test report)"}`);

function safeGit(args) {
  try {
    return execSync(`git ${args}`, { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "unknown";
  }
}
